"""Builds hooks/font.ts: an ASCII subset of Outfit as woff2, plus advance widths.

An Svg drawn as an image cannot reach the app's fonts, so each drawing with
text carries this in its own style. The mod cannot measure text at run time,
so the widths at weight 700, the widest used, size each drawing.

Source: https://github.com/Outfitio/Outfit-Fonts at 9027738, fonts/variable.
Run:
  uv run --no-project --with fonttools==4.59.0 --with brotli==1.1.0 python -I
    assets/build-font.py <Outfit[wght].ttf> hooks/font.ts
"""

import base64
import io
import sys

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

source, target = sys.argv[1], sys.argv[2]
CHARS = "".join(chr(c) for c in range(0x20, 0x7F)) + "·"

font = TTFont(source)
options = subset.Options()
options.layout_features = ["kern"]
options.hinting = False
options.name_IDs = [1, 2]
options.notdef_outline = True
subsetter = subset.Subsetter(options)
subsetter.populate(text=CHARS)
subsetter.subset(font)
font = instancer.instantiateVariableFont(font, {"wght": (400, 700)})

buffer = io.BytesIO()
font.flavor = "woff2"
font.save(buffer)
data = base64.b64encode(buffer.getvalue()).decode()

buffer.seek(0)
bold = instancer.instantiateVariableFont(TTFont(buffer), {"wght": 700})
units = bold["head"].unitsPerEm
cmap = bold.getBestCmap()
widths = {c: round(bold["hmtx"][cmap[ord(c)]][0] / units, 3) for c in CHARS}
rows = ", ".join(f"{c!r}: {w}" for c, w in widths.items())

with open(target, "w", encoding="utf-8", newline="\n") as out:
    out.write("// Generated by assets/build-font.py. Outfit, SIL OFL 1.1: see assets/OFL.txt.\n")
    out.write(f"export const FONT = '{data}'\n\n")
    out.write(f"export const ADVANCE: Readonly<Record<string, number>> = {{ {rows} }}\n")

print(f"woff2 {len(data)} base64 chars, {len(widths)} glyphs")
